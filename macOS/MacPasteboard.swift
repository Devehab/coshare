import AppKit
import SystemConfiguration
import UniformTypeIdentifiers

typealias PlatformPasteboard = MacPasteboard

extension DevicePlatform {
    static var current: DevicePlatform { .mac }

    static var defaultDeviceName: String {
        (SCDynamicStoreCopyComputerName(nil, nil) as String?) ?? "Mac"
    }
}

final class MacPasteboard: PasteboardBridge {
    private let pasteboard = NSPasteboard.general
    private var tiffProvider: TIFFProvider?

    /// Markers that password managers and clipboard tools use (nspasteboard.org) for data
    /// that should never be recorded or synced.
    private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    private static let imageTypes: [NSPasteboard.PasteboardType] = [
        .png, .tiff,
        NSPasteboard.PasteboardType(UTType.jpeg.identifier),
        NSPasteboard.PasteboardType(UTType.heic.identifier),
    ]

    var changeCount: Int { pasteboard.changeCount }

    func read(includeImages: Bool, maxImageBytes: Int, skipConcealed: Bool) -> ClipContent? {
        guard let types = pasteboard.types, !types.isEmpty else { return nil }
        let raw = Set(types.map(\.rawValue))
        if skipConcealed, !raw.isDisjoint(with: Self.privateTypes) { return nil }

        // Files copied in Finder: share a single image file, ignore everything else
        // (otherwise we would send the file's icon or its name).
        if types.contains(.fileURL) {
            guard includeImages,
                  let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                                    options: [.urlReadingFileURLsOnly: true]) as? [URL],
                  urls.count == 1, let url = urls.first,
                  let type = UTType(filenameExtension: url.pathExtension), type.conforms(to: .image),
                  let size = try? url.resourceValues(forKeys: [.fileSizeKey]).fileSize, size <= maxImageBytes,
                  let data = try? Data(contentsOf: url)
            else { return nil }
            return normalizedImage(data, uti: type.identifier)
        }

        let string = pasteboard.string(forType: .string)
        if includeImages,
           let imageType = Self.imageTypes.first(where: types.contains),
           string == nil || Self.looksLikeURL(string!) {
            guard let data = pasteboard.data(forType: imageType), data.count <= maxImageBytes else { return nil }
            return normalizedImage(data, uti: imageType.rawValue)
        }

        if let string, !string.isEmpty { return .text(string) }
        return nil
    }

    func write(_ content: ClipContent) {
        pasteboard.clearContents()
        switch content {
        case .text(let string):
            pasteboard.setString(string, forType: .string)
        case .image(let data, let uti):
            let item = NSPasteboardItem()
            let type = NSPasteboard.PasteboardType(uti)
            item.setData(data, forType: type)
            if type != .tiff {
                // Older apps only read TIFF; produce it lazily, only if someone asks.
                let provider = TIFFProvider(source: data)
                item.setDataProvider(provider, forTypes: [.tiff])
                tiffProvider = provider
            }
            pasteboard.writeObjects([item])
        }
    }

    /// TIFF is huge and not understood by iOS, so convert it to PNG before sending.
    private func normalizedImage(_ data: Data, uti: String) -> ClipContent? {
        if uti == NSPasteboard.PasteboardType.tiff.rawValue || uti == UTType.tiff.identifier {
            guard let png = NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]) else { return nil }
            return .image(png, uti: UTType.png.identifier)
        }
        return .image(data, uti: uti)
    }

    private static func looksLikeURL(_ string: String) -> Bool {
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        return trimmed.count < 2048 && !trimmed.contains(" ") && (trimmed.hasPrefix("http") || trimmed.hasPrefix("file:"))
    }
}

private final class TIFFProvider: NSObject, NSPasteboardItemDataProvider {
    private let source: Data

    init(source: Data) { self.source = source }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        guard type == .tiff, let tiff = NSImage(data: source)?.tiffRepresentation else { return }
        item.setData(tiff, forType: .tiff)
    }
}
